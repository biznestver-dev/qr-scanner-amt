/**
 * Универсальная функция поиска оборудования
 * @param {string} invInput - Инвентарный номер для поиска
 * @returns {Object|null} - Объект оборудования или null
 */
function findEquipment(invInput) {
  if (!invInput) return null;
  const key = invInput.trim().toUpperCase();
  if (window.EQUIPMENT_DB[key]) return window.EQUIPMENT_DB[key];
  for (const k in window.EQUIPMENT_DB) {
    if (window.EQUIPMENT_DB[k].inv.toUpperCase() === key) {
      return window.EQUIPMENT_DB[k];
    }
  }
  return null;
}